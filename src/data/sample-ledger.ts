export type Band = {
  label: string;
  count: number;
  predicted: number | null;
  actual: number | null;
};

const BANDS: { label: string; low: number; high: number }[] = [
  { label: "0–50%", low: 0, high: 0.5 },
  { label: "50–60%", low: 0.5, high: 0.6 },
  { label: "60–70%", low: 0.6, high: 0.7 },
  { label: "70–80%", low: 0.7, high: 0.8 },
  { label: "80–90%", low: 0.8, high: 0.9 },
  { label: "90–100%", low: 0.9, high: 1.01 },
];

export function bookSummary(trades: SampleTrade[]) {
  const correct = trades.filter((trade) => trade.result === "CORRECT").length;
  const wrong = trades.filter((trade) => trade.result === "WRONG").length;
  const pending = trades.filter((trade) => trade.result === "PENDING").length;
  const scored = correct + wrong;
  return {
    total: trades.length,
    correct,
    wrong,
    pending,
    accuracy: scored === 0 ? null : correct / scored,
  };
}

export function calibrationBands(trades: SampleTrade[]): Band[] {
  return BANDS.map((band) => {
    const rows = trades.filter(
      (trade) =>
        trade.probability != null &&
        trade.prediction !== "INSUFFICIENT_EVIDENCE" &&
        (trade.actual === "WIN" || trade.actual === "LOSS") &&
        trade.probability >= band.low &&
        trade.probability < band.high,
    );
    if (rows.length === 0) {
      return { label: band.label, count: 0, predicted: null, actual: null };
    }
    const predicted = rows.reduce((sum, trade) => sum + (trade.probability ?? 0), 0) / rows.length;
    const actual = rows.filter((trade) => trade.actual === "WIN").length / rows.length;
    return { label: band.label, count: rows.length, predicted, actual };
  });
}

export function horizonAccuracy(trades: SampleTrade[]) {
  return [5, 10, 15].map((minutes) => {
    const key = minutes === 5 ? "h5" : minutes === 10 ? "h10" : "h15";
    const known = trades.filter((trade) => trade[key] != null);
    const correct = known.filter((trade) => trade[key] === true).length;
    return {
      label: `+${minutes}m`,
      known: known.length,
      accuracy: known.length === 0 ? null : correct / known.length,
    };
  });
}

export function echoes(trade: SampleTrade) {
  const rate = trade.probability ?? 0.5;
  return [0, 1, 2, 3, 4].map((index) => ({
    id: `${trade.symbol.slice(0, 3)}-${index + 1}`,
    similarity: Math.round((0.94 - index * 0.05) * 100) / 100,
    win: index < Math.round(rate * 5),
    side: trade.side,
  }));
}
